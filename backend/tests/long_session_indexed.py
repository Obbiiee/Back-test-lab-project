DSN = os.getenv('BTL_TEST_DATABASE_URL')


def write_csv(path, ticks):
    start = datetime(2020, 1, 30, tzinfo=timezone.utc)
    seed = 20261112
    with open(path, 'w', encoding='utf-8') as out:
        out.write('Exness,Symbol,Timestamp,Bid,Ask\n')
        for i in range(ticks):
            phase = ((i * 1_103_515_245 + seed) & 0x7fffffff) % 41 - 20
            bid, spread = 200_000 + phase, 10 + i % 4
            if i == ticks - 2:
                bid, spread = 199_880, 10
            elif i == ticks - 1:
                bid, spread = 199_960, 10
            stamp = (start + timedelta(seconds=i)).strftime('%Y-%m-%d %H:%M:%S.000Z')
            out.write(f'exness,XAUUSDm,{stamp},{bid / 100:.3f},{(bid + spread) / 100:.3f}\n')


def folder_bytes(path):
    return sum(p.stat().st_size for p in Path(path).rglob('*') if p.is_file())


def facts(app, sid):
    st = app.summary(sid)
    page = app.journal_page(sid, {'limit': 32, 'cursor': None})
    return dict(through=st['throughNs'], balance=st['balance'], trades=st['completedTrades'], net=st['netCashChange'],
                orders=sorted(((o['side'], o['status'], o.get('entryPrice'), o.get('exitPrice'), o.get('net')) for o in page['orders']), key=str))


def run_tier(ticks, *, restart_every=0, budget_s=12.0, deadline_s=3000):
    name = 'btl_idx_' + uuid.uuid4().hex[:10]
    with connect(DSN) as db:
        db.autocommit = True
        db.execute(sql.SQL('CREATE DATABASE {}').format(sql.Identifier(name)))
    dsn = psycopg.conninfo.make_conninfo(DSN, dbname=name)
    migrate(dsn)
    result = dict(ticks=ticks, stack='indexed (IndexedTimelineCache, compact checkpoints, private session log)')
    with tempfile.TemporaryDirectory(prefix='riksora-idx-') as tmp:
        tmp = Path(tmp)
        t = time.monotonic(); write_csv(tmp / 'ticks.csv', ticks); result['csvSeconds'] = round(time.monotonic() - t, 1)
        t = time.monotonic()
        importer = ExnessIngestion(tmp / 'ticks.csv', tmp / 'dataset')
        try:
            version = importer.run()['datasetVersion']
        finally:
            importer.builder.store.close()
        result['ingestSeconds'] = round(time.monotonic() - t, 1); result['archiveBytes'] = folder_bytes(tmp / 'dataset')
        source = HistoricalSource(tmp / 'dataset', version, log_root=tmp / 'logs')
        scope = TrustedScope('idxqa:' + uuid.uuid4().hex, 'local:operator')
        app = ResearchApplication(dsn, scope, historical_source=source)
        method = dict(schemaVersion=1, artifact='BTL-LOCAL-METHOD-1', id='method:' + uuid.uuid4().hex, name='idx', kind='FREE_STYLE', checklistOn=False, conditions=[], riskPercent=None, rr=None)
        app.create_method(method)

        def make(app_):
            sid = 'session:' + uuid.uuid4().hex
            app_.create_session(dict(id=sid, name='idx', methodId=method['id'], initialBalance='10000', startPeriod='2020-01'))
            st = app_.summary(sid)
            app_.apply(sid, dict(schemaVersion=1, artifact='BTL-TICK-EXECUTION-COMMAND-1', sessionId=sid, commandId='command:' + uuid.uuid4().hex, expectedRevision=st['revision'],
                                 kind='ADVANCE', payload={'targetNs': str(int(st['throughNs']) + 1)}))
            view = app_.workspace(sid, {'timeframe': '1m'})
            review = dict(sessionId=sid, requestId='order:' + uuid.uuid4().hex, expectedRevision=view['state']['revision'], planId='plan:idx', planRevision=0,
                          draft=dict(side='LONG', orderType='LIMIT', workflow='PLANNED', entry='1998.90', quantity='0.01', sl='1998.00', tp='1999.50', riskPercent='1', observations=[]))
            reviewed = app_.review(review)
            app_.confirm(sid, dict(reviewId=review['requestId'], reviewHash=reviewed['reviewHash']))
            return sid

        before = db_numbers(dsn)
        cpu0, wall0 = time.process_time(), time.monotonic()
        sid = make(app)
        target = str(int(datetime(2020, 1, 30, tzinfo=timezone.utc).timestamp()) * 10**9 + (ticks + 5) * 10**9)
        st = app.summary(sid)
        request = dict(schemaVersion=1, artifact=rr.REQUEST_ARTIFACT, runId=uuid.uuid4().hex, segment=0, sessionId=sid, expectedRevision=st['revision'], targetNs=target)
        segments, resumes, t_run = [], [], time.monotonic()
        while True:
            t = time.monotonic()
            out = app.replay_run(sid, request)
            segments.append(dict(seconds=round(time.monotonic() - t, 2), chunks=out['chunks']))
            if not out['more'] or time.monotonic() - t_run > deadline_s:
                break
            request = rr.next_request(request, out)
            if restart_every and len(segments) % restart_every == 0:       # a cold worker: new application, empty timeline cache, state from PostgreSQL only
                app.close()
                t = time.monotonic()
                app = ResearchApplication(dsn, scope, historical_source=source)
                app.summary(sid)
                resumes.append(None)
                t_first = time.monotonic()
                resumes[-1] = round(t_first - t, 2)
        final = facts(app, sid)
        reached = int(final['through']) >= int(target) or out['targetReached']
        result.update(reachedTarget=reached, segments=len(segments), chunks=sum(s['chunks'] for s in segments), runWallSeconds=round(time.monotonic() - t_run, 1),
                      segmentSeconds=dict(p50=sorted(s['seconds'] for s in segments)[len(segments) // 2], max=max(s['seconds'] for s in segments)),
                      coldRestartSecondsAfterSummary=resumes, cpuSeconds=round(time.process_time() - cpu0, 1), peakRssMb=round(resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024, 1),
                      setupSeconds=round(t_run - wall0, 1), sessionLogBytes=folder_bytes(tmp / 'logs'))
        after = db_numbers(dsn)
        result['db'] = {k: after[k] - before[k] if k in ('dbBytes', 'walBytes') else after[k] for k in after}
        result['facts'] = final
        # chronological control: same archive, same action sequence, plain one-chunk commands in one hot application
        capp = ResearchApplication(dsn, scope, historical_source=source)
        cid = make(capp)
        t = time.monotonic(); n = 0
        while True:
            st = capp.summary(cid)
            if int(st['throughNs']) >= int(final['through']):
                break
            capp.apply(cid, dict(schemaVersion=1, artifact='BTL-TICK-EXECUTION-COMMAND-1', sessionId=cid, commandId='command:' + uuid.uuid4().hex, expectedRevision=st['revision'],
                                 kind='ADVANCE', payload={'targetNs': target}))
            n += 1
        ctrl = facts(capp, cid)
        result['control'] = dict(seconds=round(time.monotonic() - t, 1), chunks=n, equal=ctrl == final)
        capp.close(); app.close(); source.close_chart_history()
    return result


if __name__ == '__main__':
    ap = argparse.ArgumentParser(); ap.add_argument('--ticks', type=int, required=True); ap.add_argument('--restart-every', type=int, default=0)
    ap.add_argument('--budget', type=float, default=12.0); ap.add_argument('--out')
    a = ap.parse_args()
    os.environ['BTL_REPLAY_RUN_BUDGET_S'] = str(a.budget)
    out = run_tier(a.ticks, restart_every=a.restart_every, budget_s=a.budget)
    print(json.dumps(out, indent=1, default=str))
    if a.out:
        Path(a.out).write_text(json.dumps(out, indent=1, default=str))
