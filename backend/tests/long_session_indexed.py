"""Long-session tiers on the INDEXED timeline stack (compact checkpoints, private session log) with a SYNTHETIC tick archive written in the local-archive format.
SYNTHETIC / TEST ONLY: the data are generated by repository code; the Exness-format label is only the container the indexed provider reads. Engine path = the real one.

  BTL_TEST_DATABASE_URL=... python -m tests.long_session_indexed --ticks 16384 [--restart-every 3] [--out f.json]
"""
