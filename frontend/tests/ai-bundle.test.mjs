import assert from 'node:assert/strict';
import { mkdtemp, mkdir, writeFile, readFile, rm, readdir } from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { bundle } from '../scripts/ai-bundle.mjs';

const root = await mkdtemp(path.join(os.tmpdir(),'backtest-bundle-'));
async function snapshot(directory) {
  const result=[];
  for(const name of (await readdir(directory,{recursive:true})).sort()) {
    try { result.push([name,(await readFile(path.join(directory,name))).toString('hex')]); }
    catch(error) { if (!['EISDIR','EPERM'].includes(error.code)) throw error; }
  }
  return result;
}
try {
  await mkdir(path.join(root,'frontend/scripts'),{recursive:true});
  const configPath=path.join(root,'frontend/scripts/ai-bundle.config.json');
  const config={context:['context.md'],implementation:['source.js'],tests:['test.js'],supporting:[],currentTask:'No implementation authorized.'};
  await writeFile(configPath,JSON.stringify(config));
  for(const name of ['context.md','source.js','test.js']) await writeFile(path.join(root,name),name+'\n');
  const stats=await bundle(root); assert.equal(stats.files,7);
  const first=await readFile(path.join(root,'AI_BUNDLE/FILE_MANIFEST.json'));
  const firstTree=await snapshot(path.join(root,'AI_BUNDLE'));
  await bundle(root); assert.deepEqual(await readFile(path.join(root,'AI_BUNDLE/FILE_MANIFEST.json')),first);
  assert.deepEqual(await snapshot(path.join(root,'AI_BUNDLE')),firstTree,'Every generated byte is deterministic');
  await bundle(root,true);
  await writeFile(path.join(root,'source.js'),'changed');
  await assert.rejects(bundle(root,true),/STALE/);
  assert.deepEqual(await readFile(path.join(root,'AI_BUNDLE/FILE_MANIFEST.json')),first,'Verifier never writes');
  await bundle(root);
  assert.equal(await readFile(path.join(root,'source.js'),'utf8'),'changed','Generator never modifies source');
  await writeFile(path.join(root,'AI_BUNDLE/files/source.js'),'secondary edit');
  await assert.rejects(bundle(root,true),/Bundle changed/);
  config.implementation=['missing.js']; await writeFile(configPath,JSON.stringify(config));
  await assert.rejects(bundle(root)); assert.equal(await readFile(path.join(root,'AI_BUNDLE/files/source.js'),'utf8'),'secondary edit','Invalid input never destroys existing output');
  config.implementation=['../escape.js']; await writeFile(configPath,JSON.stringify(config)); await assert.rejects(bundle(root),/Unsafe/);
  config.implementation=['source.js']; await writeFile(configPath,JSON.stringify(config));
  await writeFile(path.join(root,'AI_BUNDLE/README.md'),'user directory'); await assert.rejects(bundle(root),/non-generated/);
  console.log('PASS bundle determinism, stale detection, bundle edits, validation, traversal and master/output protection.');
} finally {
  assert.ok(path.resolve(root).startsWith(path.resolve(os.tmpdir()) + path.sep + 'backtest-bundle-'));
  await rm(root,{recursive:true,force:true});
}
